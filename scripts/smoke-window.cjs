'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
module.exports = async ({ app, window, getStore, userDirectory, quitApp }) => {
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('lifecycle-')) return require('./lifecycle-checks.cjs')({app,window,getStore,userDirectory,quitApp});
  if (process.env.MEMOFLOW_TEST_PHASE === 'editor-interactions') return require('./editor-interaction-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'editor-detach') return require('./editor-detach-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'history-alignment') return require('./history-alignment-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'reference-navigation') return require('./reference-navigation-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'protocol-links') return require('./protocol-link-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'protocol-cold') return require('./protocol-cold-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('annotation-drafts-')) return require('./annotation-draft-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('inline-edit')) return require('./inline-edit-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('tags-cards')) return require('./tags-cards-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'list-menu') return require('./list-menu-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('refinements-')) return require('./refinement-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('updates')) return require('./update-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE?.startsWith('workspace-')) return require('./workspace-checks.cjs')({app,window,getStore,userDirectory});
  if (process.env.MEMOFLOW_TEST_PHASE === 'design') return require('./preview-window.cjs')({ app, window, getStore, userDirectory });
  const evaluate = code => window.webContents.executeJavaScript(code);
  const capturePage = async () => { for(let attempt=0;attempt<3;attempt++){try{await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');return await window.webContents.capturePage();}catch(error){if(attempt===2)throw error;await new Promise(r=>setTimeout(r,120));}} };
  async function until(code) {
    for (let i = 0; i < 100; i++) { if (await evaluate(code)) return; await new Promise(resolve => setTimeout(resolve, 60)); }
    console.error('Isolated UI diagnostic: '+JSON.stringify(await evaluate(`({text:document.querySelector('#editor')?.textContent,model:document.querySelector('#editor')?.value,html:document.querySelector('#editor')?.innerHTML,count:document.querySelectorAll('.memo').length,disabled:document.querySelector('#saveMemo')?.disabled,status:document.querySelector('#noteStatus')?.textContent,toast:document.querySelector('#toast')?.textContent})`)));
    throw Error('UI condition timed out: ' + code);
  }
  await until('document.querySelector("#editor").isContentEditable && document.querySelector("#viewTitle").textContent === "全部笔记"');
  assert.equal(await evaluate('typeof require'), 'undefined');
  assert.equal(window.webContents.getLastWebPreferences().sandbox, true);
  assert.equal(window.webContents.getLastWebPreferences().contextIsolation, true);
  assert.equal(window.webContents.getLastWebPreferences().nodeIntegration, false);
  if (process.env.MEMOFLOW_TEST_PHASE === 'first') {
    await evaluate('document.querySelector("#editor").memoEditor.setText("桌面持久化验证 #测试/桌面"); document.querySelector("#editor").dispatchEvent(new Event("input",{bubbles:true})); document.querySelector("#saveMemo").click();');
    await until('document.querySelectorAll(".memo").length === 1 && document.querySelector("#editor").textContent === ""');
    assert.equal((await getStore().readState()).memos.length, 1);
    await evaluate('document.querySelector("#editor").memoEditor.setText("重启后继续写这段草稿"); document.querySelector("#editor").dispatchEvent(new Event("input",{bubbles:true}));');
    await until('document.querySelector("#draftStatus").dataset.state === "saved"');
    await evaluate('document.querySelector("#settings").click();');
    await until('!!document.querySelector("#changeDataDirectory")');
    await evaluate('document.querySelector("#tabStorage").click()');
    const original = getStore().directory;
    await evaluate('document.querySelector("#changeDataDirectory").click();');
    await until('document.querySelector("#migrationStatus").textContent.startsWith("已切换到新位置")');
    assert.notEqual(getStore().directory, original);
    assert.equal((await getStore().readState()).memos.length, 1);
    assert.equal((await getStore().readDraft()).current.content, '重启后继续写这段草稿');
    await fs.access(path.join(original, 'state.json'));
    assert.equal(JSON.parse(await fs.readFile(path.join(userDirectory, 'storage-location.json'), 'utf8')).directory, getStore().directory);
    const { dialog } = require('electron');
    const nativeSaveDialog = dialog.showSaveDialog;
    const backupFile = path.join(userDirectory, 'exported-backup.json');
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: backupFile });
    await evaluate('document.querySelector("#exportData").click()');
    await until('document.querySelector("#backupStatus").textContent.startsWith("最近成功备份")');
    const backup = JSON.parse(await fs.readFile(backupFile, 'utf8'));
    assert.deepEqual(backup, await getStore().readState());
    const history = await fs.readFile(path.join(userDirectory, 'backup-history.json'), 'utf8');
    dialog.showSaveDialog = async () => ({ canceled: true });
    assert.equal(await evaluate('window.memoDesktop.exportFile("cancelled-backup.json","{}").then(result=>result)'), false);
    assert.equal(await fs.readFile(path.join(userDirectory, 'backup-history.json'), 'utf8'), history);
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: userDirectory });
    assert.equal(await evaluate('window.memoDesktop.exportFile("failed-backup.json","{}").then(()=>false,()=>true)'), true);
    assert.equal(await fs.readFile(path.join(userDirectory, 'backup-history.json'), 'utf8'), history);
    dialog.showSaveDialog = nativeSaveDialog;
    console.log('PASS: real JSON export, successful backup timestamp, cancellation and export failure preserve history');
    await fs.writeFile(path.join(userDirectory, '../settings-migration.png'), (await capturePage()).toPNG());
    await evaluate('document.querySelector("#closeDialog").click();');
    assert.equal(await evaluate('getComputedStyle(document.querySelector("#dialog")).display'), 'none', 'closed settings must disappear visually');
    await evaluate('document.querySelector("#settings").click();');
    await until('document.querySelector("#dialog").open && !!document.querySelector("#tabAbout")');
    await evaluate('document.querySelector("#tabAbout").click();');
    window.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'});
    window.webContents.sendInputEvent({type:'keyUp',keyCode:'Escape'});
    await until('!document.querySelector("#dialog").open');
    assert.equal(await evaluate('document.querySelector("#dialog").getClientRects().length'), 0, 'Escape must remove settings from layout');
    await evaluate('document.querySelector("#settings").click();');
    await until('document.querySelector("#dialog").open && !!document.querySelector("#saveSettings")');
    await evaluate('document.querySelector("#saveSettings").click();');
    await until('!document.querySelector("#dialog").open');
    assert.equal(await evaluate('getComputedStyle(document.querySelector("#dialog")).display'), 'none', 'saving settings must dismiss the panel');
    // Exercise real native resizing without overriding the minimum.
    window.setSize(900, 800);
    await until('innerWidth>780 && !document.querySelector("#sidebar").inert');
    window.setSize(400, 800);
    await until('innerWidth<420 && document.querySelector("#sidebar").inert');
    assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'smallest window must not overflow horizontally');
    await evaluate('document.querySelector("#mobileMenu").click()');
    await until('document.querySelector("#sidebar").classList.contains("open") && document.querySelector(".main").inert');
    await evaluate('document.querySelector("#mobileOverlay").click()');
    await until('!document.querySelector("#sidebar").classList.contains("open") && !document.querySelector(".main").inert');
    window.setSize(640, 800);
    await until('innerWidth<=780 && !!document.querySelector("#mobileMenu")?.getClientRects().length && document.querySelector("#sidebar").inert');
    assert.ok(window.getSize()[0]<=650,'native window must allow a narrow layout');
    assert.equal(await evaluate('document.querySelector("#editor").value'),'重启后继续写这段草稿');
    assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'narrow window must not overflow horizontally');
    await fs.writeFile(path.join(userDirectory, '../narrow-native.png'), (await capturePage()).toPNG());
    await new Promise(resolve => setTimeout(resolve, 500));
    console.log('PASS: native save, draft flush, renderer isolation, custom location migration and retained original');
  } else {
    await until('document.querySelector("#editor").textContent === "重启后继续写这段草稿"');
    const restoredSize = window.getSize();
    // Restoration intentionally clamps saved bounds to the current display.
    // Hosted Windows runners can have a smaller desktop than the saved 1110x800.
    const restoredArea = require('electron').screen.getDisplayMatching(window.getBounds()).workArea;
    assert.ok(Math.abs(restoredSize[0] - Math.min(640, restoredArea.width)) <= 2, 'narrow window width should restore within the display work area');
    await until('innerWidth<=780 && document.querySelector("#sidebar").inert');
    window.setSize(Math.min(1110,restoredArea.width),800);
    await until('innerWidth>780');
    assert.ok(Math.abs(restoredSize[1] - Math.max(600, Math.min(800, restoredArea.height))) <= 2, 'window height should restore within the display work area');
    assert.equal((await getStore().readState()).memos.length, 1);
    await evaluate('document.querySelector("#search").value="不存在的词"; document.querySelector("#search").dispatchEvent(new Event("input",{bubbles:true}));');
    await until('document.querySelectorAll(".memo").length === 0');
    assert.equal(await evaluate('document.querySelector("#filterBar").hidden'), false);
    assert.match(await evaluate('document.querySelector("#filterBar .querybar-count").textContent'), /笔记（0）/);
    await until('!!document.querySelector("#emptyClear")');
    await evaluate('document.querySelector("#emptyClear").click()');
    await until('document.querySelectorAll(".memo").length === 1');
    await evaluate('document.querySelector("#search").value="持久化"; document.querySelector("#search").dispatchEvent(new Event("input",{bubbles:true}));');
    await until('document.querySelectorAll(".memo").length === 1');
    await evaluate('document.querySelector(".memo-menu-button").click(); document.querySelector(".memo-menu [data-action=edit]").click();');
    await evaluate('document.querySelector("#editor").memoEditor.setText("修改后的桌面笔记 #测试/桌面"); document.querySelector("#editor").dispatchEvent(new Event("input",{bubbles:true})); document.querySelector("#saveMemo").click();');
    await until('document.querySelector("#editor").textContent === "重启后继续写这段草稿"');
    assert.equal((await getStore().readState()).memos[0].content, '修改后的桌面笔记 #测试/桌面');
    await evaluate('document.querySelector("#search").value=""; document.querySelector("#search").dispatchEvent(new Event("input",{bubbles:true})); document.querySelector("#settings").click();');
    await until('document.querySelector("#dialog").open && !!document.querySelector("#openDataFolder")');
    assert.ok((await evaluate('document.querySelector("#dialogBody").textContent')).includes("Fomo " + app.getVersion()));
    await evaluate('document.querySelector("#themeInput").value="dark"; document.querySelector("#saveSettings").click();');
    await until('document.body.classList.contains("dark") && !document.querySelector("#dialog").open');
    await evaluate('document.querySelector("#settings").click();');
    await until('!!document.querySelector("#themeInput")');
    await evaluate('document.querySelector("#themeInput").value="light"; document.querySelector("#saveSettings").click();');
    await until('!document.body.classList.contains("dark") && !document.querySelector("#dialog").open');
    await evaluate('document.querySelector(".memo-menu-button").click(); document.querySelector(".memo-menu [data-action=delete]").click();');
    await until('document.querySelectorAll(".memo").length === 0');
    await evaluate('document.querySelector("[data-view=trash]").click();');
    await until('document.querySelectorAll(".memo").length === 1');
    await evaluate('document.querySelector("[data-action=restore]").click();');
    await until('document.querySelectorAll(".memo").length === 0');
    await evaluate('document.querySelector("[data-view=all]").click();');
    await until('document.querySelectorAll(".memo").length === 1');
    const active = (await getStore().readState()).memos[0];
    await fs.access(path.join(getStore().directory, 'Memos', active.id + '.md'));
    await until('document.querySelector("#viewTitle").textContent === "全部笔记"');
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    const screenshot = await capturePage();
    await fs.writeFile(path.join(userDirectory, '../desktop-smoke.png'), screenshot.toPNG());
    console.log('PASS: restart restores notes and draft; search, edit, theme, trash/restore, Markdown projection');
  }
  window.close();
};
