'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const memoListeners=new Set(), memoLinkErrors=new Set(), pendingMemoIds=[], pendingLinkErrors=[];
ipcRenderer.on('desktop:open-memo',(_event,id)=>{if(memoListeners.size){for(const callback of memoListeners)callback(id);}else pendingMemoIds.push(id);});
ipcRenderer.on('desktop:open-note-link-error',()=>{if(memoLinkErrors.size){for(const callback of memoLinkErrors)callback();}else pendingLinkErrors.push(true);});
contextBridge.exposeInMainWorld('memoDesktop', {
  titlebarOverlay: process.platform==='win32',
  setTitlebarTheme: (dark,dimmed=false) => ipcRenderer.invoke('desktop:set-titlebar-theme',dark,dimmed),
  init: () => ipcRenderer.invoke('memo:init'),
  save: (base, desired) => ipcRenderer.invoke('memo:save', base, desired),
  readState: () => ipcRenderer.invoke('memo:read'),
  draft: (_key, value) => ipcRenderer.invoke('memo:draft', value),
  readDraft: () => ipcRenderer.invoke('memo:read-draft'),
  detachComposer: payload => ipcRenderer.invoke('desktop:detach-composer', payload),
  backupInfo: () => ipcRenderer.invoke('desktop:backup-info'),
  configureBackups: value => ipcRenderer.invoke('desktop:backup-configure',value),
  backupNow: () => ipcRenderer.invoke('desktop:backup-now'),
  previewBackup: id => ipcRenderer.invoke('desktop:backup-preview',id),
  previewComposeDraftBackup: id => ipcRenderer.invoke('desktop:backup-preview-compose-draft',id),
  restoreComposeDraftBackup: request => ipcRenderer.invoke('desktop:backup-restore-compose-draft',request),
  deleteBackup: id => ipcRenderer.invoke('desktop:backup-delete',id),
  restoreBackup: request => ipcRenderer.invoke('desktop:backup-restore',request),
  restoreAiConversationBackup: request => ipcRenderer.invoke('desktop:backup-restore-ai-conversations',request),
  storageInfo: () => ipcRenderer.invoke('desktop:storage-info'),
  previewObsidian: () => ipcRenderer.invoke('desktop:obsidian-preview'),
  previewObsidianReview: () => ipcRenderer.invoke('desktop:obsidian-preview-review'),
  applyObsidianReview: () => ipcRenderer.invoke('desktop:obsidian-apply-review'),
  connectObsidian: code => ipcRenderer.invoke('desktop:obsidian-connect',code),
  disconnectObsidian: () => ipcRenderer.invoke('desktop:obsidian-disconnect'),
  applyObsidian: () => ipcRenderer.invoke('desktop:obsidian-apply'),
  confirmMissingObsidianDeletion: () => ipcRenderer.invoke('desktop:obsidian-confirm-missing'),
  cancelObsidianTrash: () => ipcRenderer.invoke('desktop:obsidian-cancel-trash'),
  finalizeObsidianTrash: () => ipcRenderer.invoke('desktop:obsidian-finalize-trash'),
  resolveObsidianConflict: choice => ipcRenderer.invoke('desktop:obsidian-resolve',choice),
  cleanupAttachments: names => ipcRenderer.invoke('desktop:cleanup-attachments', names),
  attachmentInfo: () => ipcRenderer.invoke('desktop:attachment-info'),
  purge: ids => ipcRenderer.invoke('memo:purge', ids),
  info: () => ipcRenderer.invoke('desktop:info'),
  aiSettings: () => ipcRenderer.invoke('ai:get-settings'),
  readAiConversations: () => ipcRenderer.invoke('ai:read-conversations'),
  saveAiConversations: value => ipcRenderer.invoke('ai:save-conversations', value),
  saveAiSettings: value => ipcRenderer.invoke('ai:save-settings', value),
  testAi: value => ipcRenderer.invoke('ai:test', value),
  aiComplete: value => { const requestId = 'ai-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8); return ipcRenderer.invoke('ai:complete', { ...value, requestId }); },
  aiCompleteRequest: value => { const requestId = 'ai-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8); return { requestId, result: ipcRenderer.invoke('ai:complete', { ...value, requestId }) }; },
  aiCancel: requestId => ipcRenderer.invoke('ai:cancel', requestId),
  aiCancelStream: () => ipcRenderer.invoke('ai:cancel-stream'),
  importBackup: options => ipcRenderer.invoke('memo:import-backup', options),
  aiStream: (value, onChunk) => { const requestId = 'ai-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8); const listener = (_event, message) => { if (message?.requestId === requestId) onChunk?.(String(message.delta || '')); }; ipcRenderer.on('ai:stream:chunk', listener); return ipcRenderer.invoke('ai:stream', { ...value, requestId }).finally(() => ipcRenderer.removeListener('ai:stream:chunk', listener)); },
  aiStreamRequest: (value, onChunk) => { const requestId = 'ai-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8); const listener = (_event, message) => { if (message?.requestId === requestId) onChunk?.(String(message.delta || '')); }; ipcRenderer.on('ai:stream:chunk', listener); return { requestId, result: ipcRenderer.invoke('ai:stream', { ...value, requestId }).finally(() => ipcRenderer.removeListener('ai:stream:chunk', listener)) }; },
  aiAgentRequest: (value, onEvent) => { const requestId = 'agent-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8); const listener = (_event, message) => { if(message?.requestId===requestId) onEvent?.(message); }; ipcRenderer.on('ai:agent:event', listener); return {requestId,result:ipcRenderer.invoke('ai:agent',{...value,requestId}).finally(()=>ipcRenderer.removeListener('ai:agent:event',listener))}; },
  scheduleReview: settings => ipcRenderer.invoke('desktop:schedule-review', settings),
  onOpenReview: callback => ipcRenderer.on('desktop:open-review', () => callback()),
  setAutoLaunch: value => ipcRenderer.invoke('desktop:set-auto-launch', value),
  setTrayAction: value => ipcRenderer.invoke('desktop:set-tray-action', value),
  setNewNoteCloseAfterPublish: value => ipcRenderer.invoke('desktop:set-new-note-close-after-publish', value),
  setCloseToTray: value => ipcRenderer.invoke('desktop:set-close-to-tray', value),
  openData: () => ipcRenderer.invoke('desktop:open-data'),
  changeDataDirectory: () => ipcRenderer.invoke('desktop:change-data'),
  openReleases: () => ipcRenderer.invoke('desktop:releases'),
  updateStatus: () => ipcRenderer.invoke('desktop:update-status'),
  checkUpdates: () => ipcRenderer.invoke('desktop:update-check'),
  downloadUpdate: () => ipcRenderer.invoke('desktop:update-download'),
  updatePreference: auto => ipcRenderer.invoke('desktop:update-preference', auto),
  installUpdate: () => ipcRenderer.invoke('desktop:update-install'),
  updatePrepared: (ok,requestId) => ipcRenderer.invoke('desktop:update-prepared', ok,requestId),
  onUpdateState: callback => ipcRenderer.on('desktop:update-state', (_event, state) => callback(state)),
  onPrepareUpdate: callback => ipcRenderer.on('desktop:prepare-update', (_event,requestId) => callback(requestId)),
  onUpdateAborted: callback => ipcRenderer.on('desktop:update-aborted', () => callback()),
  onShowUpdates: callback => ipcRenderer.on('desktop:show-updates', () => callback()),
  openNote: (id,floating=false) => ipcRenderer.invoke('desktop:open-note',id,floating),
  onOpenMemo: callback => { memoListeners.add(callback); while(pendingMemoIds.length)callback(pendingMemoIds.shift()); return ()=>memoListeners.delete(callback); },
  onOpenMemoLinkError: callback => { memoLinkErrors.add(callback); while(pendingLinkErrors.length){pendingLinkErrors.shift();callback();} return ()=>memoLinkErrors.delete(callback); },
  onNoteSaved: callback => ipcRenderer.on('desktop:note-saved',(_event,id)=>callback(id)),
  exportFile: (name, content) => ipcRenderer.invoke('desktop:export', name, content),
  shareImage: request => ipcRenderer.invoke('desktop:share-image', request),
  finishClose: ok => ipcRenderer.invoke('desktop:finish-close', ok),
  onClose: callback => ipcRenderer.on('desktop:prepare-close', () => callback()),
  onFocusEditor: callback => ipcRenderer.on('desktop:focus-editor', () => callback()),
  onSettings: callback => ipcRenderer.on('desktop:settings', () => callback()),
  onOpenInsight: callback => ipcRenderer.on('desktop:open-insight', () => callback()),
  onEditorCommand: callback => ipcRenderer.on('desktop:editor-command', (_event, command) => { if (command==='undo'||command==='redo') callback(command); })
});
